// Rebuilds src/legacy.js from ../client.src.js (the hand-written source; the
// shipped ./client.js at the package root is the Vite bundle).
//
// client.src.js is the single-file source artifact: it registers itself through
// window.__ModuleLoader__ and borrows the host React. Inside the bundled build we
// need the same ~7000 lines as a plain module factory instead, so this script
// swaps the loader wrapper for `export function createStudio(React, h)` and hands
// StudioPage / StudioIcon back to the caller.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(here, '../../client.src.js')
const target = resolve(here, '../src/legacy.js')

let text = readFileSync(source, 'utf8')

// client.js ships with CRLF; the transforms below are written for LF.
text = text.replace(/\r\n/g, '\n')

const header = /window\.__ModuleLoader__\.load\(\{\s*\n\s*id: 'dsh-studio',\s*\n\s*factory\(require\) \{\s*\n\s*const React = require\('react'\)\s*\n\s*const h = React\.createElement\s*\n/
if (!header.test(text)) {
  console.error('make-legacy: loader header not found in client.js')
  process.exit(1)
}
text = text.replace(header, 'export function createStudio(React, h) {\n')

// The loader's `return { inject, apply }` block becomes the factory's return
// value, with the two components appended so the bridge can mount them itself.
const marker = '\n    return {\n      inject:'
const at = text.lastIndexOf(marker)
if (at < 0) {
  console.error('make-legacy: loader return block not found in client.js')
  process.exit(1)
}
text =
  text.slice(0, at + 1) +
  `    return {
      inject: ['slots'],
      apply(ctx) {
        const disposers = []
        disposers.push(ctx.slots.inject('main', () => ctx.slots.register(
          { name: 'main', key: PANEL_ID }, StudioPage,
        )))
        disposers.push(ctx.slots.inject('sidebar.panellist', () => ctx.slots.register(
          { name: 'sidebar.panellist', id: PANEL_ID, order: 12, label: () => '需求&任务工作空间' }, StudioIcon,
        )))
        const cleanup = () => { for (const dispose of disposers.splice(0).reverse()) dispose() }
        if (typeof ctx.effect === 'function') ctx.effect(() => cleanup)
        return cleanup
      },
      StudioPage,
      StudioIcon,
      useUIKit,
    }
}
`

const banner = `/**
 * dsh-studio legacy panel — generated by web/scripts/make-legacy.mjs from ../client.js.
 *
 * Do not edit by hand: change client.js (the artifact that ships without a build)
 * and re-run \`node web/scripts/make-legacy.mjs\`.
 */

`
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, banner + text)
console.log(`make-legacy: wrote ${target} (${text.length} chars)`)
